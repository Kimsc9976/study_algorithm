
from collections import deque

def solution(s):
    """
    [Deque + Stack] 괄호 회전하기

    문자열을 왼쪽으로 회전시키면서, 올바른 괄호 문자열이
    만들어지는 경우의 수를 구하는 문제이다.

    1. 문자열 회전 (Deque)
       - 왼쪽으로 한 칸 회전한다는 것은
         맨 앞 문자를 꺼내 맨 뒤에 붙이는 것과 같다.
       - deque의 rotate(-1)을 사용하면 O(1)에 회전할 수 있다.
       - 문자열 길이가 N이라면 N번 회전했을 때 원래 문자열로 돌아온다.
         따라서 총 N번만 검사하면 모든 회전 경우를 확인할 수 있다.

    2. 올바른 괄호 검증 (Stack)
       - 프로그래머스 12973 '짝지어 제거하기'와 유사한 방식이다.
       - 문자열을 왼쪽부터 순회하면서 여는 괄호를 Stack에 저장한다.
       - 닫는 괄호가 등장하면 Stack의 마지막 여는 괄호를 꺼내
         올바른 쌍인지 Dictionary를 통해 확인한다.

       검증 실패 조건:
       (1) Stack이 비었는데 닫는 괄호가 등장한 경우
           -> 대응되는 여는 괄호가 존재하지 않는다.
       (2) Stack에서 꺼낸 여는 괄호와 닫는 괄호의 짝이 다른 경우
           -> 괄호의 순서가 잘못되었다.
       (3) 모든 문자를 검사했지만 Stack에 괄호가 남아있는 경우
           -> 닫히지 않은 여는 괄호가 존재한다.

    3. Stack이 비어있는지만 확인하면 안 되는 이유
       예) s = "[)(]"

       '[' -> ['[']   (여는 괄호 push)
       ')' -> []      (여는 괄호 pop, 하지만 짝이 다름)

       이때 Stack은 비어 있지만 올바른 괄호 문자열이 아니다.
       따라서 is_valid를 별도로 관리해야 한다.

       최종 성공 조건:
       - is_valid == True
       - len(stack) == 0
       두 조건을 모두 만족해야 한다.

    시간복잡도 : O(N^2)
    - 전체 문자열을 N번 회전한다.
    - 매 회전마다 최대 N개의 문자를 검사한다.
    - rotate(-1)은 O(1)이므로 전체 O(N^2)이다.

    공간복잡도 : O(N)
    - 문자열을 저장하는 Deque와 괄호 검증용 Stack을 사용한다.
    """

    _lst = deque(s)
    _dict = {"{": "}", "[": "]", "(": ")"}
    answer = 0

    # N번 회전하면서 모든 시작 위치에 대한 괄호 문자열 검증
    for _ in range(len(s)):
        # 이전 회전의 검증 결과가 영향을 주지 않도록 매번 초기화
        _stk = []
        is_valid = True

        for c in _lst:
            # 1. 여는 괄호라면 Stack에 저장
            if c in _dict:
                _stk.append(c)

            # 2. 닫는 괄호라면 짝이 맞는지 확인
            else:
                # 대응되는 여는 괄호가 없는데 닫는 괄호가 등장
                # 이미 올바르지 않은 문자열이므로 즉시 중단
                if len(_stk) == 0:
                    is_valid = False
                    break

                # 가장 최근에 열린 괄호부터 닫혀야 하므로 pop()
                bracket = _stk.pop()

                # 여는 괄호와 닫는 괄호의 종류가 다르면 실패
                if _dict.get(bracket) != c:
                    is_valid = False
                    break

        # 3. 모든 괄호가 올바르게 매칭되었는지 최종 확인
        # Stack이 비어 있어도 중간에 매칭 실패했을 수 있으므로
        # is_valid 조건까지 함께 검사해야 한다.
        if len(_stk) == 0 and is_valid:
            answer += 1

        # 4. 왼쪽으로 한 칸 회전하여 다음 경우를 검사
        _lst.rotate(-1)

    return answer
